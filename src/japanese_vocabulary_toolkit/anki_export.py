from __future__ import annotations

from pathlib import Path
import hashlib
from html import escape

from .deck_build import BuildRow
from .card_templates import CardLayout


def _stable_int(namespace: str, value: str, digits: int = 9) -> int:
    raw = hashlib.sha256(f"{namespace}:{value}".encode("utf-8")).hexdigest()
    return int(str(int(raw[:15], 16))[:digits])


def stable_guid(source_id: str, reading: str) -> str:
    # Keep the historical namespace so decks created by pre-renaming versions
    # update in place rather than duplicating notes.
    return hashlib.sha1(f"kotoba-anki:{source_id}:{reading}".encode("utf-8")).hexdigest()[:20]


_ANKI_FIELD = {
    "expression": "Expression",
    "reading": "Reading",
    "definition_ja": "Definition",
    "input_meaning": "InputMeaning",
    "jmdict_gloss": "JmdictGloss",
    "pos": "PartOfSpeech",
    "tags": "Tags",
    "notes": "Notes",
    "level": "Level",
    "frequency": "FrequencyRank",
}


def _template_piece(field: str, *, front: bool) -> str:
    name = _ANKI_FIELD[field]
    css = "expression" if field == "expression" else ("reading" if field == "reading" else "card-field")
    # Conditional sections avoid blank blocks when a preset requests optional data.
    return f"{{{{#{name}}}}}<div class=\"{css}\">{{{{{name}}}}}</div>{{{{/{name}}}}}"


def _html_for_layout(layout: CardLayout) -> tuple[str, str]:
    qfmt = "".join(_template_piece(x, front=True) for x in layout.front)
    back_body = "".join(_template_piece(x, front=False) for x in layout.back)
    afmt = '{{FrontSide}}<hr id="answer">' + back_body
    return qfmt, afmt


def write_apkg(path: Path, rows: list[BuildRow], deck_name: str, *, layout: CardLayout) -> None:
    try:
        import genanki
    except ImportError as exc:  # pragma: no cover - environment-dependent
        raise RuntimeError(
            "Anki export requires genanki. Install the project normally with "
            "`python -m pip install -e .` (genanki is a project dependency)."
        ) from exc

    # One stable superset model allows users to change presets without changing
    # note identity or losing hidden metadata.
    model_id = _stable_int("model", "kotoba-anki-recognition-v1")
    deck_id = _stable_int("deck", deck_name)
    qfmt, afmt = _html_for_layout(layout)
    model = genanki.Model(
        model_id,
        "Validated Card Generator v1",
        fields=[
            # Preserve the original seven-field prefix and model ID so decks
            # generated by the personal prototype have the best possible
            # upgrade path. New public fields are appended only.
            {"name": "Expression"},
            {"name": "Reading"},
            {"name": "Definition"},
            {"name": "SourceId"},
            {"name": "Level"},
            {"name": "FrequencyRank"},
            {"name": "SourceIndex"},
            {"name": "InputMeaning"},
            {"name": "JmdictGloss"},
            {"name": "PartOfSpeech"},
            {"name": "Tags"},
            {"name": "Notes"},
        ],
        templates=[{"name": "Vocabulary", "qfmt": qfmt, "afmt": afmt}],
        css="""
.card { font-family: 'Noto Sans JP', 'Yu Gothic', sans-serif; text-align: center; font-size: 24px; color: #222; background: #fff; }
.expression { font-size: 42px; margin: 24px 0; }
.reading { font-size: 28px; margin: 14px 0 18px; }
.card-field { font-size: 22px; line-height: 1.55; text-align: left; max-width: 42rem; margin: 10px auto; white-space: pre-line; }
""",
    )
    deck = genanki.Deck(deck_id, deck_name)

    class StableNote(genanki.Note):
        def __init__(self, *, source_id: str, reading: str, **kwargs):
            self._source_id = source_id
            self._reading = reading
            super().__init__(**kwargs)

        @property
        def guid(self):
            return stable_guid(self._source_id, self._reading)

    def br(text: str) -> str:
        return text.replace("\n", "<br>")

    for row in sorted(rows, key=lambda x: x.source_index):
        note = StableNote(
            model=model,
            source_id=row.source_id,
            reading=row.reading,
            fields=[
                row.expression,
                row.reading,
                br(row.definition),
                row.source_id,
                row.level,
                str(row.frequency_rank or ""),
                str(row.source_index),
                br(row.input_meanings),
                br(row.jmdict_glosses),
                row.pos,
                row.tags,
                br(row.note),
            ],
        )
        deck.add_note(note)

    path.parent.mkdir(parents=True, exist_ok=True)
    genanki.Package(deck).write_to_file(str(path))


def _preview_value(row: BuildRow, field: str) -> str:
    return {
        "expression": row.expression,
        "reading": row.reading,
        "definition_ja": row.definition,
        "input_meaning": row.input_meanings,
        "jmdict_gloss": row.jmdict_glosses,
        "pos": row.pos,
        "tags": row.tags,
        "notes": row.note,
        "level": row.level,
        "frequency": str(row.frequency_rank or ""),
    }[field]


def write_preview_html(path: Path, rows: list[BuildRow], *, layout: CardLayout, limit: int = 100) -> None:
    cards = []
    for row in sorted(rows, key=lambda x: x.source_index)[:limit]:
        front = "".join(
            f'<div class="{("expression" if f == "expression" else "preview-field")}">{escape(_preview_value(row, f))}</div>'
            for f in layout.front if _preview_value(row, f)
        )
        back = "".join(
            f'<div class="{("reading" if f == "reading" else "preview-field")}">{escape(_preview_value(row, f)).replace(chr(10), "<br>")}</div>'
            for f in layout.back if _preview_value(row, f)
        )
        cards.append(f'<article class="card"><div class="front">{front}</div><div class="back">{back}</div></article>')
    html = """<!doctype html><meta charset="utf-8"><title>Japanese Vocabulary Toolkit preview</title>
<style>body{font-family:system-ui,'Noto Sans JP','Yu Gothic',sans-serif;max-width:900px;margin:40px auto;padding:0 20px;background:#f4f4f4}.card{background:white;border:1px solid #ddd;border-radius:10px;padding:24px;margin:18px 0}.expression{font-size:38px;text-align:center;margin-bottom:18px}.reading{font-size:26px;margin:8px 0}.preview-field{font-size:20px;line-height:1.5;margin:8px 0}</style>""" + "\n".join(cards)
    path.write_text(html, encoding="utf-8")
