from __future__ import annotations

from dataclasses import dataclass
from html.parser import HTMLParser
import re


@dataclass(frozen=True)
class DefinitionBlock:
    part_of_speech: str | None
    senses: tuple[str, ...]


class _DictionaryHTMLParser(HTMLParser):
    """Extract grammatical blocks and concise sense text from koreader-dicts HTML."""

    def __init__(self) -> None:
        super().__init__()
        self.blocks: list[DefinitionBlock] = []
        self._in_div = False
        self._depth = 0
        self._pos: str | None = None
        self._sense_parts: list[str] = []
        self._current: list[str] = []
        self._capture = False
        self._capture_qualifier = False
        self._tag_stack: list[tuple[str, dict[str, str | None]]] = []
        self._have_seen_pos = False

    def handle_starttag(self, tag: str, attrs) -> None:
        attrs_d = dict(attrs)
        self._tag_stack.append((tag, attrs_d))
        if tag == "div":
            if not self._in_div:
                self._in_div = True
                self._depth = 1
                self._pos = None
                self._sense_parts = []
                self._have_seen_pos = False
            else:
                self._depth += 1
            return
        if not self._in_div:
            return
        if tag == "i" and not self._have_seen_pos and not attrs_d.get("style"):
            self._capture = True
            self._current = []
        elif tag == "i" and self._have_seen_pos and attrs_d.get("style"):
            self._capture = True
            self._capture_qualifier = True
            self._current = []
        elif tag in {"span", "b"}:
            self._capture = True
            self._current = []

    def handle_endtag(self, tag: str) -> None:
        if self._in_div and self._capture and tag in {"i", "span", "b"}:
            text = " ".join("".join(self._current).split())
            if tag == "i" and not self._have_seen_pos and self._pos is None:
                self._pos = text or None
                self._have_seen_pos = True
            elif tag == "i" and self._capture_qualifier:
                if text:
                    self._sense_parts.append(f"__QUAL__{text}")
                self._capture_qualifier = False
            elif text and not _is_numbering(text):
                self._sense_parts.append(text)
            self._capture = False
            self._current = []
        if tag == "br" and self._in_div:
            self._sense_parts.append("\n")
        if tag == "div" and self._in_div:
            self._depth -= 1
            if self._depth == 0:
                senses = _coalesce_senses(self._sense_parts)
                self.blocks.append(DefinitionBlock(self._pos, tuple(senses)))
                self._in_div = False
        if self._tag_stack:
            self._tag_stack.pop()

    def handle_data(self, data: str) -> None:
        if self._capture:
            self._current.append(data)


def _is_numbering(text: str) -> bool:
    stripped = text.strip().rstrip(".")
    return stripped.isdigit()


def _coalesce_senses(parts: list[str]) -> list[str]:
    senses: list[str] = []
    current: list[str] = []
    for part in parts:
        if part == "\n":
            text = " ".join(current).strip()
            if text:
                senses.append(text)
            current = []
        else:
            current.append(part)
    text = " ".join(current).strip()
    if text:
        senses.append(text)
    return list(dict.fromkeys(senses))


def definition_blocks(value: str) -> list[DefinitionBlock]:
    parser = _DictionaryHTMLParser()
    parser.feed(value)
    return parser.blocks


def _sense_reading_label(sense: str) -> str | None:
    match = re.match(r"^【([^】]+)】", sense.strip())
    return match.group(1) if match else None


def is_reference_definition(value: str) -> bool:
    """Return True when every extracted sense is only a cross-reference stub."""
    senses = [sense for block in definition_blocks(value) for sense in block.senses if sense]
    if not senses:
        return False
    reference_patterns = (
        re.compile(r"^[「『]?(?:.+?)[」』]?を?参照[。．]?$"),
        re.compile(r"^[「『]?(?:.+?)[」』]?に同じ[。．]?$"),
        re.compile(r"^.+?の漢字表記[。．]?$"),
    )
    return all(any(pattern.match(sense.strip()) for pattern in reference_patterns) for sense in senses)


_QUALIFIER_MARKER = "__QUAL__"
_SKIP_QUALIFIERS = ("archaic", "dated", "obsolete", "dialectal", "internet", "slang")


def _split_qualifier(text: str) -> tuple[str | None, str]:
    if not text.startswith(_QUALIFIER_MARKER):
        return None, text
    rest = text[len(_QUALIFIER_MARKER):]
    # The marker is followed by the qualifier then the actual sense text.
    # Qualifiers generated by this source are parenthetical, e.g. (dated).
    m = re.match(r"(\([^)]*\))\s*(.*)$", rest)
    if m:
        return m.group(1), m.group(2).strip()
    parts = rest.split(" ", 1)
    return parts[0], parts[1].strip() if len(parts) > 1 else ""


def _skip_qualified_sense(text: str) -> bool:
    qualifier, _ = _split_qualifier(text)
    if not qualifier:
        return False
    # Styled italic text that is not a parenthetical qualifier is an example
    # sentence/quotation in this dictionary source, not a dictionary sense.
    if not (qualifier.startswith("(") and qualifier.endswith(")")):
        return True
    q = qualifier.lower()
    return any(token in q for token in _SKIP_QUALIFIERS)


_ETYM_PAREN = re.compile(
    r"[（(][^（）()]{0,50}(?:ラテン語|ギリシャ語|英語|フランス語|ドイツ語|語源|由来)[^（）()]{0,50}[）)]"
)
_LABEL_ONLY = re.compile(r"^【[^】]+】[。．]?$" )
_DEPENDENT_REFERENCE = re.compile(
    r"(?:語義\s*[0-9一二三四五六七八九十]+"
    r"|(?<![0-9第])[1-9](?:\.|\s)+(?:を|で|から|の|に|へ|と|が|は|より)"
    r"|上記(?:の|語義)?|前述(?:の|語義)?|前項|この語義)"
)


def _clean_display_sense(sense: str) -> str:
    """Remove mechanical dictionary clutter without inventing new wording."""
    text = " ".join(sense.split()).strip()
    qualifier, payload = _split_qualifier(text)
    if qualifier is not None:
        text = payload

    # Wiktionary-derived entries often prefix synonym lists before an em dash.
    if " — " in text:
        prefix, explanation = text.split(" — ", 1)
        if explanation and len(prefix) < 80:
            text = explanation.strip()

    # A spelling label by itself is metadata, not a definition.
    if _LABEL_ONLY.fullmatch(text):
        return ""

    # Remove compact etymological asides that do not help recognition review.
    text = _ETYM_PAREN.sub("", text)
    text = re.sub(r"\s+([。．、，])", r"\1", text).strip()
    return text


def _split_spelling_label(text: str) -> tuple[tuple[str, ...], str] | None:
    m = re.match(r"^【([^】]+)】\s*(.*)$", text.strip())
    if not m:
        return None
    forms = tuple(x.strip() for x in re.split(r"[・、,／/]", m.group(1)) if x.strip())
    return forms, m.group(2).strip()


def _strip_reading_prefix(text: str, preferred_reading: str | None) -> tuple[str, bool]:
    if not preferred_reading:
        return text, False
    m = re.match(r"^[（(]([^）)]+)[）)]\s*(.*)$", text.strip())
    if not m:
        return text, False
    label = m.group(1).strip()
    # Parenthetical kana labels are commonly used to distinguish readings.
    if label == preferred_reading:
        return m.group(2).strip(), True
    return text, False


def _candidate_senses(
    value: str,
    preferred_pos: str | None = None,
    preferred_reading: str | None = None,
    preferred_expression: str | None = None,
) -> list[str]:
    blocks = definition_blocks(value)
    if preferred_pos:
        matching = [b for b in blocks if b.part_of_speech == preferred_pos]
        if matching:
            blocks = matching

    senses = [sense for block in blocks for sense in block.senses if sense]

    # Some entries explicitly label homonymous readings with 【かな】.
    if preferred_reading:
        labelled = [s for s in senses if _sense_reading_label(s) == preferred_reading]
        if labelled:
            senses = labelled

    # Kana headwords frequently segment homographs with standalone spelling
    # labels such as 【備える・具える】 or 【著す】. When such labels exist,
    # use the original written form to select the appropriate segment.
    if preferred_expression:
        segmented: list[str] = []
        active_forms: tuple[str, ...] | None = None
        saw_spelling_label = False
        matched_label = False
        for raw in senses:
            # For segmentation, inspect the post-dash payload before label-only
            # cleanup removes it. This preserves markers such as
            # "synonyms — 【備える・具える】".
            label_source = raw.strip()
            if " — " in label_source:
                _, label_source = label_source.split(" — ", 1)
                label_source = label_source.strip()
            cleaned = _clean_display_sense(raw)
            label = _split_spelling_label(label_source)
            if label:
                forms, remainder = label
                # A pure kana label equal to the reading is a reading marker,
                # not an orthographic segmentation marker.
                if not (preferred_reading and len(forms) == 1 and forms[0] == preferred_reading):
                    saw_spelling_label = True
                    active_forms = forms
                    is_match = preferred_expression in forms
                    matched_label = matched_label or is_match
                    if remainder and is_match:
                        segmented.append(remainder)
                    continue
            if active_forms is not None:
                if preferred_expression in active_forms:
                    segmented.append(raw)
            elif not saw_spelling_label:
                segmented.append(raw)
        if saw_spelling_label:
            senses = segmented if matched_label else []

    # Parenthetical reading prefixes such as （きち） / （きじ） can separate
    # homographs inside one record. Keep matching senses when such labels occur.
    if preferred_reading and senses:
        prefixed = []
        saw_reading_prefix = False
        for sense in senses:
            stripped, matched = _strip_reading_prefix(sense, preferred_reading)
            if matched:
                saw_reading_prefix = True
                prefixed.append(stripped)
            elif not re.match(r"^[（(][ぁ-ゖァ-ヺー]+[）)]", sense.strip()):
                prefixed.append(sense)
        if saw_reading_prefix:
            senses = prefixed

    return senses

def selected_display_senses(
    value: str,
    max_senses: int = 2,
    preferred_pos: str | None = None,
    preferred_reading: str | None = None,
    preferred_expression: str | None = None,
) -> list[str]:
    unique: list[str] = []
    for sense in _candidate_senses(value, preferred_pos, preferred_reading, preferred_expression):
        if _skip_qualified_sense(sense):
            continue
        cleaned = _clean_display_sense(sense)
        if cleaned and cleaned not in unique:
            unique.append(cleaned)
        if len(unique) >= max_senses:
            break
    return unique


def _normalise_for_circular_check(text: str) -> str:
    """Normalize a short Japanese gloss for self-reference comparison."""
    text = _clean_display_sense(text)
    text = re.sub(r"^[「『（(【\\s]+|[」』）)】。．、，\\s]+$", "", text)
    return text.strip()


def _is_circular_display_sense(
    sense: str,
    preferred_expression: str | None,
    preferred_reading: str | None,
) -> bool:
    """True when a displayed sense merely repeats the word or reading.

    This is deliberately strict: only near-bare self references are rejected;
    definitions that happen to contain the headword remain valid.
    """
    normalized = _normalise_for_circular_check(sense)
    if not normalized:
        return False
    targets = {
        _normalise_for_circular_check(value)
        for value in (preferred_expression, preferred_reading)
        if value
    }
    return normalized in targets


def strip_circular_display_senses(
    value: str,
    preferred_expression: str | None,
    preferred_reading: str | None,
) -> str:
    """Remove only bare self-reference lines using the existing circular check."""
    kept = [
        line.strip()
        for line in value.splitlines()
        if line.strip() and not _is_circular_display_sense(
            line, preferred_expression, preferred_reading
        )
    ]
    return "\n".join(kept)


def definition_quality_warnings(
    value: str,
    preferred_pos: str | None = None,
    preferred_reading: str | None = None,
    preferred_expression: str | None = None,
) -> list[str]:
    """Flag concrete defects in the *displayed* definition.

    This deliberately does not infer that an entry is bad merely because the
    source dictionary has many senses. Editorial usefulness is a separate
    problem from mechanical card cleanliness.
    """
    raw_senses = _candidate_senses(value, preferred_pos, preferred_reading, preferred_expression)
    displayed = selected_display_senses(value, 2, preferred_pos, preferred_reading, preferred_expression)
    warnings: list[str] = []

    if not displayed:
        warnings.append("empty-display-definition")
        return warnings

    if any(_is_circular_display_sense(s, preferred_expression, preferred_reading) for s in displayed):
        warnings.append("circular-display-definition")

    if any(_DEPENDENT_REFERENCE.search(s) for s in displayed):
        warnings.append("dependent-sense-reference")

    # Recognition cards should be glanceable; long entries deserve editorial review.
    if any(len(s) > 80 for s in displayed):
        warnings.append("long-display-sense")

    # If the raw first candidate was only a spelling label, record the parser
    # defect even though we can skip it and continue to a real sense.
    if raw_senses and _LABEL_ONLY.fullmatch(_clean_display_sense(raw_senses[0]) or raw_senses[0].strip()):
        warnings.append("spelling-label-skipped")

    return list(dict.fromkeys(warnings))




def has_explicit_expression_label(value: str, preferred_expression: str | None) -> bool:
    """Whether the dictionary text explicitly associates a sense with this spelling.

    Used only as positive evidence. Absence of a label says nothing for ordinary
    entries, but matters when a kana record merges several JMdict homonyms.
    """
    if not preferred_expression:
        return False
    for block in definition_blocks(value):
        for raw in block.senses:
            text = raw.strip()
            if " — " in text:
                _, text = text.split(" — ", 1)
                text = text.strip()
            label = _split_spelling_label(text)
            if label and preferred_expression in label[0]:
                return True
            m = re.match(r"^[（(]([^）)]+)[）)]", text)
            if m and re.search(r"[一-龯々〆ヶ]", m.group(1)):
                forms = [x.strip() for x in re.split(r"[・、,／/]", m.group(1)) if x.strip()]
                if preferred_expression in forms:
                    return True
    return False



def expression_prefix_conflicts(definition: str, preferred_expression: str | None) -> bool:
    """Detect an explicit written-form label that contradicts the requested word."""
    if not preferred_expression:
        return False
    first = (definition.splitlines() or [""])[0].strip()
    m = re.match(r"^[（(]([^）)]+)[）)]", first)
    if not m:
        return False
    label = m.group(1).strip()
    # Kana here is normally a reading label; kanji-bearing text is a spelling label.
    if not re.search(r"[一-龯々〆ヶ]", label):
        return False
    forms = [x.strip() for x in re.split(r"[・、,／/]", label) if x.strip()]
    return bool(forms) and preferred_expression not in forms

def transitivity_conflicts(value: str, parts_of_speech: tuple[str, ...]) -> bool:
    """Use explicit dictionary transitivity tags only when they contradict JMdict.

    Absence of a tag is not evidence. This is intentionally conservative.
    """
    lower = [p.lower() for p in parts_of_speech]
    expects_transitive = any("transitive verb" in p and "intransitive" not in p for p in lower)
    expects_intransitive = any("intransitive verb" in p for p in lower)
    html_lower = value.lower()
    has_intransitive = "(intransitive)" in html_lower
    # Avoid treating the substring in "intransitive" as "transitive".
    has_transitive = bool(re.search(r"(?<!in)\(transitive\)", html_lower))
    if expects_transitive and has_intransitive and not has_transitive:
        return True
    if expects_intransitive and has_transitive and not has_intransitive:
        return True
    return False

def concise_definition(
    value: str,
    max_senses: int = 2,
    preferred_pos: str | None = None,
    preferred_reading: str | None = None,
    preferred_expression: str | None = None,
) -> str:
    return "\n".join(selected_display_senses(value, max_senses, preferred_pos, preferred_reading, preferred_expression))
